primeiro_valor = int(input("Digite o primeiro valor: "))
segundo_valor = int(input("Digite o segundo valor: "))

soma = primeiro_valor + segundo_valor
subtacao = primeiro_valor - segundo_valor
multiplicacao = primeiro_valor * segundo_valor
divisao = primeiro_valor / segundo_valor

print(f"A soma entre {primeiro_valor} + {segundo_valor} é {soma}")
print(f"A subtração entre {primeiro_valor} - {segundo_valor} é {subtacao}")
print(f"A multiplicação entre {primeiro_valor} * {segundo_valor} é {multiplicacao}")
print(f"A divisão entre {primeiro_valor} / {segundo_valor} é {divisao}")
